const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");

const source = fs.readFileSync("src/detector.js", "utf8");
const context = { globalThis: {}, self: {} };
vm.runInNewContext(source, context);
const { sanitize } = context.globalThis.PiiDetector;

const result = sanitize("Email jane@example.com, card 4111 1111 1111 1111, IP 192.168.1.10.");
assert.equal(result.text, "Email [EMAIL], card [CARD], IP [IP_ADDRESS].");
assert.equal(result.replacements.length, 3);
assert.equal(sanitize("Call 1-800-FLOWERS for help.").text, "Call [PHONE] for help.");
assert.equal(sanitize("India: +91 98765 43210 or 09876543210").text, "India: [PHONE] or [PHONE]");
assert.equal(sanitize("PAN ABCPD1234F, Aadhaar 2345 6789 0124").text, "PAN [PAN], Aadhaar [AADHAAR]");
assert.equal(sanitize("Invalid PAN ABCD1234F").text, "Invalid PAN ABCD1234F");
assert.equal(sanitize("2345 6789 0124\n5871-2046-9932\n948215673489\n7012 3456 7890\n3629-8154-0076\n8456 1209 3847").text, "[AADHAAR]\n[AADHAAR]\n[AADHAAR]\n[AADHAAR]\n[AADHAAR]\n[AADHAAR]");
assert.equal(sanitize("6190-4institute").text, "6190-4institute");
assert.equal(sanitize("Hi team, please write to priya.sharma+invoices@mail.acme.co.in about the refund.").text, "Hi team, please write to [EMAIL] about the refund.");
assert.equal(sanitize("Customer Aadhaar is 948215673489 and PAN is XYZCK5678F.").text, "Customer Aadhaar is [AADHAAR] and PAN is [PAN].");
assert.equal(sanitize("Aadhaar (2345-6789-0124) was verified at the branch.").text, "Aadhaar ([AADHAAR]) was verified at the branch.");
assert.equal(sanitize("Aadhaar 2345  6789\n0124 was verified.").text, "Aadhaar [AADHAAR] was verified.");
assert.equal(sanitize("Call me on +91 98765 43210 after 6 pm, or try 09876543210.").text, "Call me on [PHONE] after 6 pm, or try [PHONE].");
assert.equal(sanitize("You can reach US support at (415) 555-0132 anytime.").text, "You can reach US support at [PHONE] anytime.");
assert.equal(sanitize("Charge it to 5555 5555 5555 4444, expiry 12/28.").text, "Charge it to [CARD], expiry 12/28.");
assert.equal(sanitize("Backup card: 4111-1111-1111-1111.").text, "Backup card: [CARD].");
assert.equal(sanitize("Amex: 3782 822463 10005.").text, "Amex: [CARD].");
assert.equal(sanitize("Email me at jane@example.com.").text, "Email me at [EMAIL].");
assert.equal(sanitize("The server at 10.0.0.25 keeps timing out, but 8.8.8.8 is fine.").text, "The server at [IP_ADDRESS] keeps timing out, but [IP_ADDRESS] is fine.");
assert.equal(sanitize("jane@example.com wrote to jane@example.com from 192.168.1.10").text, "[EMAIL] wrote to [EMAIL] from [IP_ADDRESS]");
assert.equal(sanitize("Hi, I'm Ravi. PAN ABCPD1234F, Aadhaar 2345 6789 0124, mobile +91 98765 43210, email ravi.k@example.in. Please update my KYC.").text, "Hi, I'm Ravi. PAN [PAN], Aadhaar [AADHAAR], mobile [PHONE], email [EMAIL]. Please update my KYC.");
assert.equal(sanitize("The number 4111 1111 1111 1112 is not a valid card.").text, "The number 4111 1111 1111 1112 is not a valid card.");
assert.equal(sanitize("Reference 0123 4567 8901 and 1234 5678 9012 are internal IDs.").text, "Reference 0123 4567 8901 and 1234 5678 9012 are internal IDs.");
assert.equal(sanitize("Tracking number 9482156734891 shipped today.").text, "Tracking number 9482156734891 shipped today.");
assert.equal(sanitize("Code ABCZD1234F is not a PAN.").text, "Code ABCZD1234F is not a PAN.");
assert.equal(sanitize("Bad IPs: 256.1.1.1 and 999.999.999.999.").text, "Bad IPs: 256.1.1.1 and 999.999.999.999.");
assert.equal(sanitize("Version 2.0.1 shipped on 17/10/2026 for ₹1,25,000.").text, "Version 2.0.1 shipped on 17/10/2026 for ₹1,25,000.");
assert.equal(sanitize("Ping me at user@ later.").text, "Ping me at user@ later.");
assert.equal(sanitize("Lowercase PAN abcpd1234f is also sensitive.").text, "Lowercase PAN [PAN] is also sensitive.");
assert.equal(sanitize("id2345 6789 0124x should remain an internal ID.").text, "id2345 6789 0124x should remain an internal ID.");
assert.equal(sanitize("US SSN 123-45-6789 is no longer detected.").text, "US SSN 123-45-6789 is no longer detected.");
assert.equal(sanitize("Order 1-800-555 is too short to be a phone number.").text, "Order 1-800-555 is too short to be a phone number.");
assert.equal(sanitize("jane@example.com", { email: false }).text, "jane@example.com");
assert.equal(sanitize("Mail jane@example.com, ip 10.0.0.25", { email: false }).text, "Mail jane@example.com, ip [IP_ADDRESS]");
assert.equal(sanitize("Order 2345 6789 0123 shipped.").text, "Order 2345 6789 0123 shipped.");
assert.equal(sanitize("a@b.co 4111 1111 1111 1111").replacements.length, 2);
console.log("detector tests passed");